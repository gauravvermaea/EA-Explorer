"""Builds services/api/eax/seed/industry_grm.py (the TOGAF Government Reference Model in the library, R12.1) from
tools/grm_taxonomy.py.

    python tools/build_grm_model.py

Each sector and function becomes a Function, each service a Service its function realizes, each driver for change a
Driver associated with its sector. Keys (S01, S01.F01, S01.F01.V01, S01.D01) follow the order in the taxonomy, so
add new entries at the end of their list to keep the guids of what is already there.
"""

from __future__ import annotations

import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "services" / "api" / "eax" / "seed" / "industry_grm.py"
sys.path.insert(0, str(ROOT / "tools"))

HEAD = '''"""The TOGAF Series Guide: Government Reference Model (GRM, G21D, 2025) as a reference model in the library (Release 12,
R12.1, D815, D879; the owner has The Open Group's permission for this use).

The GRM's three levels on ArchiMate 4: each **sector** (Level 1, a business area of government) and each **function**
(Level 2, what government does at an aggregate level) is a Function, the function a child of its sector (composed of
it); each **service** (Level 3, what government does at component level) is a Service its function realizes and a
child of it. Each sector's **drivers for change** are Drivers associated with it. The names are the guide's; every
description is written in EA Explorer's own words, because the guide's text is not for redistribution: read the guide
itself for its full text (www.opengroup.org/library/g21d). Generic, with no country variant (D814). Keys are stable
across releases (S01, S01.F01, S01.F01.V01, S01.D01): the guids are made from them.

Generated by tools/build_grm_model.py from tools/grm_taxonomy.py; do not edit by hand.
"""

'''


def build() -> tuple[list, list]:
    """The entities and relationships, from the taxonomy."""
    from grm_taxonomy import GRM
    ents, rels = [], []
    for i, (sector, sdesc, functions, drivers) in enumerate(GRM, 1):
        sk = f"S{i:02d}"
        ents.append((sk, "Function", sector, f"Government Reference Model, Level 1 sector. {sdesc}", None, {}))
        for j, (fn, fdesc, services) in enumerate(functions, 1):
            fk = f"{sk}.F{j:02d}"
            ents.append((fk, "Function", fn, f"Government Reference Model, Level 2 function of {sector}. {fdesc}", sk, {}))
            rels.append((sk, "Composition", fk, ""))
            for k, (sv, vdesc) in enumerate(services, 1):
                vk = f"{fk}.V{k:02d}"
                ents.append((vk, "Service", sv, f"Government Reference Model, Level 3 service of {fn}. {vdesc}", fk, {}))
                rels.append((fk, "Realization", vk, ""))
        for d, (dn, ddesc) in enumerate(drivers, 1):
            dk = f"{sk}.D{d:02d}"
            ents.append((dk, "Driver", dn, f"Government Reference Model, a driver for change in {sector}. {ddesc}", None, {}))
            rels.append((dk, "Association", sk, "drives change in"))
    return ents, rels


def main() -> int:
    """Writes the module."""
    ents, rels = build()
    OUT.write_text(HEAD + "# (key, ArchiMate 4 type code, name, description, parent key, {attribute code: value})\nENTITIES = "
                   + pprint.pformat(ents, width=118) + "\n\n# (source key, relationship type, target key, name)\nRELATIONSHIPS = "
                   + pprint.pformat(rels, width=118) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(ents)} entities, {len(rels)} relationships")
    return 0


if __name__ == "__main__":
    sys.exit(main())
