"""Builds services/api/eax/seed/industry_dbrm.py (the TOGAF Digital Business Reference Model in the library, R12.3)
from tools/dbrm_taxonomy.py.

    python tools/build_dbrm_model.py

Every level is a Grouping (no new types, D887), each a child of the level above and aggregated by it: the four domains,
the ten core elements, their parts, and under Digital Competencies the DPBoK's four contexts and their competencies.
Each competency is associated with the Digital Enablement pillar it enables (the guide's Table 4-1). Keys follow the
order in the taxonomy (D1, D1.E1, D1.E1.P1, ...): add new entries at the end of their list to keep the guids.
"""

from __future__ import annotations

import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "services" / "api" / "eax" / "seed" / "industry_dbrm.py"
sys.path.insert(0, str(ROOT / "tools"))

HEAD = '''"""The TOGAF Series Guide: Digital Business Reference Model (DBRM, G21H, 2025) as a reference model in the library
(Release 12, R12.3, D858, D879; the owner has The Open Group's permission for this use).

The DBRM's four domains (Digital, Strategy, Structural, Operational), its ten core elements and their parts, as
Groupings, each a child of the one above and aggregated by it (no new types, D887); under Digital Competencies, the
DPBoK's four contexts and their competencies, each competency associated with the Digital Enablement pillar it enables.
Names are the guide's; every description is EA Explorer's own, because the guide's text is not for redistribution:
read the guide for its full text (www.opengroup.org/library/g21h). Used in phase B of a Digital transformation project.

Generated by tools/build_dbrm_model.py from tools/dbrm_taxonomy.py; do not edit by hand.
"""

'''


def build() -> tuple[list, list]:
    """The entities and relationships, from the taxonomy."""
    from dbrm_taxonomy import CONTEXTS, DBRM, ENABLES
    ents, rels, key_of = [], [], {}

    def add(key, name, desc, parent):
        ents.append((key, "Grouping", name, desc, parent, {}))
        key_of[name] = key
        if parent:
            rels.append((parent, "Aggregation", key, ""))

    for i, (domain, ddesc, elements) in enumerate(DBRM, 1):
        dk = f"D{i}"
        add(dk, domain, f"Digital Business Reference Model, domain. {ddesc}", None)
        for j, (el, edesc, parts) in enumerate(elements, 1):
            ek = f"{dk}.E{j}"
            add(ek, el, f"Digital Business Reference Model, core element of the {domain}. {edesc}", dk)
            for k, (part, pdesc) in enumerate(parts, 1):
                add(f"{ek}.P{k}", part, f"Digital Business Reference Model, part of {el}. {pdesc}", ek)
    comp = key_of["Digital Competencies"]
    for c, (ctx, cdesc, items) in enumerate(CONTEXTS, 1):
        ck = f"{comp}.C{c}"
        add(ck, ctx, f"Digital Practitioner Body of Knowledge context, under Digital Competencies. {cdesc}", comp)
        for n, item in enumerate(items, 1):
            add(f"{ck}.K{n}", item, f"Digital competency of {ctx}.", ck)
    for item, pillar in ENABLES:
        rels.append((key_of[item], "Association", key_of[pillar], "enables"))
    return ents, rels


def main() -> int:
    """Writes the module."""
    ents, rels = build()
    OUT.write_text(HEAD + "# (key, ArchiMate 4 type code, name, description, parent key, {attribute code: value})\nENTITIES = "
                   + pprint.pformat(ents, width=118) + "\n\n# (source key, relationship type, target key, name)\nRELATIONSHIPS = "
                   + pprint.pformat(rels, width=118) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(ents)} entities, {len(rels)} relationships")
    return 0


if __name__ == "__main__":
    sys.exit(main())
