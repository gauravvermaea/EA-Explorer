def test_the_safe_fixes_are_what_was_agreed():
    assert I.SAFE == ("reindex", "validate", "sequence") and I.ROWS == ("orphans",)
    assert I.fix_sql({"key": "reindex", "target": '"core"."x_idx"'}) == 'REINDEX INDEX CONCURRENTLY "core"."x_idx"'
    assert I.fix_sql({"key": "sequence", "target": json.dumps({"sequence": '"s"."q"', "to": 41})}) == "SELECT setval('\"s\".\"q\"', 41, true)"
    with pytest.raises(ValueError):
        I.fix_sql({"key": "orphans", "target": "{}"})


