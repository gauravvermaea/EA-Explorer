def test_a_backup_counts_only_when_recent_and_good():
    from datetime import UTC, datetime, timedelta
    fresh = (datetime.now(UTC) - timedelta(hours=3)).strftime("%Y%m%dT%H%M%SZ")
    old = (datetime.now(UTC) - timedelta(days=3)).strftime("%Y%m%dT%H%M%SZ")
    assert I.backed_up_recently(ask=lambda: [{"name": f"{fresh}-x", "status": "ok"}])
    assert not I.backed_up_recently(ask=lambda: [{"name": f"{old}-x", "status": "ok"}])
    assert not I.backed_up_recently(ask=lambda: [{"name": f"{fresh}-x", "status": "failed"}])


