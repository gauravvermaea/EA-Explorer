@pytest.mark.skipif(not DSN, reason="needs EAX_MIGRATED_TEST_DSN (a real PostgreSQL)")
def test_a_broken_database_is_found_safely_fixed_and_its_orphans_removed_on_a_yes(broken_db, monkeypatch):
    name, connect = broken_db
    out = I.check([name], connect=connect)
    keys = sorted(f["key"] for f in out["findings"] if f["level"] != "info")
    assert keys == ["orphans", "sequence", "sequence", "validate"], out["findings"]     # parent's identity and child's serial
    done = I.safe_fixes(out["findings"], connect=connect)
    by = {d["sql"].split()[0]: d["status"] for d in done}
    assert by["SELECT"] == "done"
    assert any(d["sql"].startswith("ALTER TABLE") and d["status"].startswith("failed") for d in done)   # orphans first
    again = I.check([name], connect=connect)
    assert sorted(f["key"] for f in again["findings"] if f["level"] != "info") == ["orphans", "validate"]
    orphan = next(f for f in again["findings"] if f["key"] == "orphans")
    monkeypatch.setenv("EAX_OPS_TOKEN", "integrity-test-key")
    p = I.repair_preview(orphan, connect=connect)
    assert p["count"] == 1 and p["sample"][0]["note"] == "orphan"
    r = I.repair(p["confirm"], connect=connect)
    assert r["removed"] == 1 and r["rows"][0]["note"] == "orphan"
    I.safe_fixes([f for f in I.check([name], connect=connect)["findings"]], connect=connect)    # now it validates
    assert not [f for f in I.check([name], connect=connect)["findings"] if f["level"] != "info"]
